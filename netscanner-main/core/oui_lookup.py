def format_mac(mac: str) -> str:
    """Format MAC address to standard colon-separated uppercase XX:XX:XX:XX:XX:XX format."""
    if not mac:
        return "00:00:00:00:00:00"
    clean = re.sub(r'[^a-fA-F0-9]', '', mac).upper()
    if len(clean) == 12:
        return ":".join(clean[i:i+2] for i in range(0, 12, 2))
    return mac.upper()

def lookup_vendor(mac: str) -> str:
    """Perform OUI lookup for a given MAC address."""
    if not mac:
        return "Unknown"
    formatted = format_mac(mac)
    prefix = formatted.replace(":", "")[:6]
    return OUI_DATABASE.get(prefix, "Unknown")

def guess_device_type(vendor: str, hostname: str) -> str:
    """Estimate device category based on vendor and hostname clues."""
    host_lower = (hostname or "").lower()
    vendor_lower = (vendor or "").lower()

    if "router" in host_lower or "gateway" in host_lower or "cisco" in vendor_lower or "tp-link" in vendor_lower or "netgear" in vendor_lower or "asus" in vendor_lower:
        return "Router"
    if "raspberry" in vendor_lower or "espressif" in vendor_lower:
        return "IoT Device"
    if "printer" in host_lower or "canon" in vendor_lower or "epson" in vendor_lower or "xerox" in vendor_lower or "ricoh" in vendor_lower:
        return "Printer"
    if "tv" in host_lower or "chromecast" in host_lower or "roku" in host_lower or "firestick" in host_lower or "apple tv" in host_lower:
        return "Smart TV"
    if "iphone" in host_lower or "ipad" in host_lower or "android" in host_lower or "galaxy" in host_lower or "samsung" in vendor_lower or "xiaomi" in vendor_lower:
        return "Mobile"
    if "apple" in vendor_lower or "macbook" in host_lower or "dell" in vendor_lower or "lenovo" in vendor_lower or "hp" in vendor_lower or "intel" in vendor_lower or "desktop" in host_lower or "laptop" in host_lower:
        return "Computer"
    return "Unknown Device"
